#include <iostream> // Стандартты енгізу/шығару кітапханасын қосу
using namespace std; // std атаулы кеңістікті қолдану

// Евклид алгоритмі бойынша екі санның ЕҮОБ-ын табатын рекурсивті функция
int gcd(int a, int b) {
    if (b == 0)  // Егер b = 0 болса, онда а - ЕҮОБ
        return a;
    return gcd(b, a % b);  // Рекурсивті қадам: a мен b-нің қалдығын табу
}

int main() {
    int num1, num2;  // Екі бүтін санды сақтайтын айнымалыларды жариялау
    cout << "Enter two numbers:";  // Пайдаланушыдан екі сан енгізу туралы хабарлама шығару
    cin >> num1 >> num2;  // Пайдаланушыдан екі санды енгізу
    cout << "Greatest common divisor:" << gcd(num1, num2) << endl;  // ЕҮОБ нәтижесін шығару
    return 0;  // Бағдарламаның дұрыс аяқталуы
}
